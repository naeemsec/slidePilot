package com.slidepilot.app;

/** Boot-compatible keyboard: no report ID, eight input bytes, one LED output byte. */
public final class KeyboardReport {
    private KeyboardReport() {}
    public enum Command {
        NEXT(0, 0x4e), PREVIOUS(0, 0x4b), START(0, 0x3e),
        CURRENT(0x02, 0x3e), END(0, 0x29), BLACK(0, 0x05);
        final int modifier, usage;
        Command(int modifier, int usage) { this.modifier = modifier; this.usage = usage; }
    }
    public static byte[] press(Command command) {
        return new byte[] {(byte) command.modifier, 0, (byte) command.usage, 0, 0, 0, 0, 0};
    }
    public static byte[] release() { return new byte[8]; }
    public static byte[] descriptor() {
        return new byte[] {
            0x05, 0x01, 0x09, 0x06, (byte) 0xa1, 0x01,
            0x05, 0x07, 0x19, (byte) 0xe0, 0x29, (byte) 0xe7,
            0x15, 0x00, 0x25, 0x01, 0x75, 0x01, (byte) 0x95, 0x08, (byte) 0x81, 0x02,
            (byte) 0x95, 0x01, 0x75, 0x08, (byte) 0x81, 0x01,
            (byte) 0x95, 0x05, 0x75, 0x01, 0x05, 0x08, 0x19, 0x01, 0x29, 0x05,
            (byte) 0x91, 0x02, (byte) 0x95, 0x01, 0x75, 0x03, (byte) 0x91, 0x01,
            (byte) 0x95, 0x06, 0x75, 0x08, 0x15, 0x00, 0x25, 0x65,
            0x05, 0x07, 0x19, 0x00, 0x29, 0x65, (byte) 0x81, 0x00, (byte) 0xc0
        };
    }
}
